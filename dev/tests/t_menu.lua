-- окно выбора: открывается, пауза, экраны, реактор одной строкой, настройки, BACK, лаборатория F1
TESTS = arg[0]:match("^(.*)[/\\]") or "."
dofile(TESTS .. "/mock.lua")
LOAD(arg[1])
run(600)
check(TITLE() and TITLE():find("NEW RUN"), "chooser opens on a new run")
check(PAUSED == true, "game is paused while choosing")
check(logHas("Loaded! v"), "load message")
goto_("MUTATOR: NONE"); key("RETURN")
check(TITLE() and TITLE():find("MUTATORS"), "mutators screen")
goto_("REACTOR: FAILURE"); key("RIGHT_ARROW")
check(hasText("REACTOR: CRITICAL"), "reactor level cycles right")
key("RIGHT_ARROW"); check(hasText("REACTOR: MELTDOWN"), "reactor level 3")
key("RETURN"); check(hasText("MUTATOR: MELTDOWN"), "picking a reactor level returns to main")
key("BACKSPACE")
goto_("SETTINGS"); key("RETURN")
check(TITLE() and TITLE():find("SETTINGS"), "settings screen")
check(hasText("DEVELOPER LAB"), "lab row visible when unlocked")
key("BACKSPACE"); check(TITLE() and TITLE():find("NEW RUN"), "backspace returns to main")
startRun()
check(PAUSED == false, "game unpaused after start")
check(logHas("Run started"), "run started")
key("F1"); run(100)
check(has("+  GON+ LAB  +"), "F1 opens the lab when unlocked")
check(hasText("SECTION:"), "lab has sections")
for _ = 1, 12 do if hasText("PREVIEW NIGHTMARE") then break end key("RIGHT_ARROW") end
check(hasText("PREVIEW NIGHTMARE"), "darkness section")
key("F1"); run(100)
key("F1"); run(100)
check(hasText("SECTION:"), "F1 closes and reopens the lab")
DONE("menu")
